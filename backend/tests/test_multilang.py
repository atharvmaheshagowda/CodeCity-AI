def test_minified_and_generated_code_detection():
    # Minified by extension
    assert is_minified_or_generated("", "jquery.min.js")[0] is True
    # Minified by long line
    long_line_code = "var a = 1;\n" + ("x" * 2000) + "\n"
    assert is_minified_or_generated(long_line_code, "bundle.js")[0] is True

    # Generated headers
    gen_code_1 = "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n"
    assert is_minified_or_generated(gen_code_1, "user.pb.go")[0] is True

    gen_code_2 = "/* @generated by Thrift compiler */\n"
    assert is_minified_or_generated(gen_code_2, "service.java")[0] is True

    # Clean normal code
    clean_code = "function add(a, b) {\n  return a + b;\n}\n"
    assert is_minified_or_generated(clean_code, "math.js")[0] is False


