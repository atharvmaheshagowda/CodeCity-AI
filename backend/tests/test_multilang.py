# 7. ZIP SECURITY: ZIP-SLIP & ZIP-BOMB PROTECTION
# ==============================================================

def test_zip_slip_security_rejection():
    temp_dir = tempfile.mkdtemp(prefix="codecity_slip_")
    zip_path = os.path.join(temp_dir, "malicious.zip")
    extract_target = os.path.join(temp_dir, "extracted")
    os.makedirs(extract_target, exist_ok=True)

    try:
        # Build a malicious ZIP containing a path traversal ../../attack.txt
        with zipfile.ZipFile(zip_path, "w") as zf:
            zf.writestr("../../escaped_file.txt", "attack content")

        with pytest.raises(InputSecurityError, match="Zip-Slip"):
            extract_zip_safely(zip_path, extract_target)

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


def test_zip_bomb_size_rejection():
    temp_dir = tempfile.mkdtemp(prefix="codecity_bomb_")
    zip_path = os.path.join(temp_dir, "bomb.zip")
    extract_target = os.path.join(temp_dir, "extracted")
    os.makedirs(extract_target, exist_ok=True)

    try:
        with zipfile.ZipFile(zip_path, "w") as zf:
            # Entry limit check: test with max_entries=5
            for i in range(10):
                zf.writestr(f"file_{i}.txt", "data")

        with pytest.raises(InputSecurityError, match="ZIP bomb protection"):
            extract_zip_safely(zip_path, extract_target, max_entries=5)

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


