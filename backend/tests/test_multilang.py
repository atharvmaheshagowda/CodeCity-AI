# 9. END-TO-END MULTI-LANGUAGE CITY ANALYSIS INTEGRATION
# ==============================================================

@pytest.mark.parametrize("lang_name,files_dict", [
    ("python", {
        "src/app.py": "from .core import run\ndef start(): run()\n",
        "src/core.py": "def run(): return 42\n"
    }),
    ("javascript", {
        "lib/index.js": "const math = require('./math');\nfunction compute() { return math.add(1, 2); }\n",
        "lib/math.js": "exports.add = (a, b) => a + b;\n"
    }),
    ("typescript", {
        "src/index.ts": "import { add } from './math';\nexport const x = add(2, 3);\n",
        "src/math.ts": "export function add(a: number, b: number): number { return a + b; }\n"
    }),
    ("go", {
        "go.mod": "module myapp\n\ngo 1.21\n",
        "pkg/calc/add.go": "package calc\nfunc Add(a, b int) int { return a + b }\n",
        "main.go": "package main\nimport \"myapp/pkg/calc\"\nfunc main() { calc.Add(1, 2) }\n"
    }),
    ("c", {
        "include/util.h": "#ifndef UTIL_H\n#define UTIL_H\nint util(void);\n#endif\n",
        "src/util.c": "#include \"util.h\"\nint util(void) { return 1; }\n",
        "src/main.c": "#include \"util.h\"\nint main() { return util(); }\n"
    }),
    ("rust", {
        "Cargo.toml": '[package]\nname = "mycrate"\nversion = "0.1.0"\n',
        "src/lib.rs": "pub mod utils;\nuse crate::utils::add;\npub fn run() { add(1, 2); }\n",
        "src/utils.rs": "pub fn add(a: i32, b: i32) -> i32 { a + b }\n"
    }),
    ("ruby", {
        "lib/app.rb": "require_relative 'utils'\nclass App; def run; Utils.calc; end; end\n",
        "lib/utils.rb": "module Utils; def self.calc; 1; end; end\n"
    }),
    ("php", {
        "src/App.php": "namespace App;\nuse App\\Utils;\nclass App { function run() { return Utils::calc(); } }\n",
        "src/Utils.php": "namespace App;\nclass Utils { static function calc() { return 1; } }\n"
    }),
])
def test_end_to_end_multilang_payload_generation(lang_name, files_dict):
    temp_dir = tempfile.mkdtemp(prefix=f"codecity_e2e_{lang_name}_")
    try:
        for rel_p, content in files_dict.items():
            full_p = os.path.join(temp_dir, rel_p)
            os.makedirs(os.path.dirname(full_p), exist_ok=True)
            with open(full_p, "w", encoding="utf-8") as f:
                f.write(content)

        payload = generate_city_payload(f"e2e_{lang_name}", f"E2E {lang_name.upper()}", temp_dir, is_static=True)

        assert payload["repo_id"] == f"e2e_{lang_name}"
        assert payload["summary"]["total_files"] >= 2
        assert len(payload["files"]) >= 2
        assert "graph_coverage" in payload
        assert "languages" in payload
        assert any(l["name"] == lang_name for l in payload["languages"])

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


