def test_multi_lang_dependency_graph_and_coverage():
    temp_dir = tempfile.mkdtemp(prefix="codecity_test_graph_")
    try:
        # Create JS/TS fixture
        os.makedirs(os.path.join(temp_dir, "src", "components"), exist_ok=True)
        with open(os.path.join(temp_dir, "src", "components", "Button.tsx"), "w") as f:
            f.write("export function Button() { return null; }\n")
        with open(os.path.join(temp_dir, "src", "App.tsx"), "w") as f:
            f.write("import { Button } from './components/Button';\nexport function App() { Button(); return null; }\n")

        # Create Go fixture
        os.makedirs(os.path.join(temp_dir, "pkg", "math"), exist_ok=True)
        with open(os.path.join(temp_dir, "go.mod"), "w") as f:
            f.write("module myapp\n\ngo 1.21\n")
        with open(os.path.join(temp_dir, "pkg", "math", "calc.go"), "w") as f:
            f.write("package math\nfunc Add(a, b int) int { return a + b }\n")
        with open(os.path.join(temp_dir, "main.go"), "w") as f:
            f.write("package main\nimport \"myapp/pkg/math\"\nfunc main() { math.Add(1, 2) }\n")

        files = [
            "src/components/Button.tsx",
            "src/App.tsx",
            "pkg/math/calc.go",
            "main.go"
        ]

        G, report = build_multi_language_dependency_graph(temp_dir, files)

        # Assert TS import edge resolved
        assert G.has_edge("src/App.tsx", "src/components/Button.tsx")
        # Assert Go import edge resolved
        assert G.has_edge("main.go", "pkg/math/calc.go")

        # Assert coverage report
        assert report["overall_coverage"] > 0.5
        assert "typescript" in report["per_language"]
        assert "go" in report["per_language"]

    finally:
        shutil.rmtree(temp_dir, ignore_errors=True)


