def test_metrics_extraction_across_languages():
    # Python (Radon)
    py_code = "def calc(x):\n    if x > 0:\n        return 1\n    return 0\n"
    py_m = calculate_metrics(py_code, "test.py", "python")
    assert py_m["complexity_method"] == "radon"
    assert py_m["mean_complexity"] == 2.0
    assert py_m["loc"] == 4

    # JavaScript (Lizard)
    js_code = "function calc(x) { if (x > 0) return 1; return 0; }"
    js_m = calculate_metrics(js_code, "test.js", "javascript")
    assert js_m["complexity_method"] == "lizard"
    assert js_m["mean_complexity"] == 2.0

    # Go (Lizard)
    go_code = "package main\nfunc calc(x int) int {\n    if x > 0 {\n        return 1\n    }\n    return 0\n}\n"
    go_m = calculate_metrics(go_code, "test.go", "go")
    assert go_m["complexity_method"] == "lizard"
    assert go_m["mean_complexity"] == 2.0

    # Unsupported / fallback (keyword branching)
    sql_code = "SELECT * FROM users WHERE status = 'active' AND (age > 18 OR role = 'admin');"
    sql_m = calculate_metrics(sql_code, "query.sql", "sql")
    assert sql_m["is_approximate"] is True
    assert sql_m["mean_complexity"] >= 2.0


